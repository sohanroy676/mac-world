def step_jain(thr_by_ap):
    """Per-step Jain index over APs (1.0 when every AP is idle)."""
    x = np.array([thr_by_ap[a] for a in sorted(thr_by_ap)])
    den = len(x) * (x ** 2).sum(axis=0)
    return np.where(den > 0, x.sum(axis=0) ** 2 / np.where(den > 0, den, 1), 1.0)


