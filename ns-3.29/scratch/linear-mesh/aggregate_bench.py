with open(os.path.join(args.out, "timeseries.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["topo", "mode", "step", "aggregate_mbps", "jain", "mean_reward"] +
               ["thr_ap%d_mbps" % a for a in range(1, MAX_AP + 1)] + ["cw_ap%d" % a for a in range(1, MAX_AP + 1)])
    for t in topos:
        n_t = len(next(iter(next(iter(runs[t].values())).values()))["aps"])
        for m in [m for m in MODES if m in runs[t]]:
            S = list(runs[t][m].values())
            agg = np.mean([s["tot"] for s in S], axis=0)
            jn = np.mean([step_jain(s["thr"]) for s in S], axis=0)
            rw = np.mean([np.mean([s["reward"][a] for a in s["aps"]], axis=0) for s in S], axis=0)
            thr = [np.mean([s["thr"][a] for s in S], axis=0) for a in S[0]["aps"]]
            cw = [np.mean([s["cw"][a] for s in S], axis=0) for a in S[0]["aps"]]
            for i in range(len(agg)):
                w.writerow([t, m, i, "%.4f" % agg[i], "%.4f" % jn[i], "%.5f" % rw[i]] +
                           ["%.4f" % thr[k][i] if k < n_t else "" for k in range(MAX_AP)] +
                           ["%.1f" % cw[k][i] if k < n_t else "" for k in range(MAX_AP)])
