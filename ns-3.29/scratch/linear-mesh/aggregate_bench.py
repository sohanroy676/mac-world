"""v1.1.0: aggregate benchmark runs into tables (mean +- 95% CI over seeds, paired delta vs BEB) and plots.
Usage (from this directory):
  ../../venv/bin/python aggregate_bench.py results/bench-<ts> [results/bench-<ts2> ...] [--out docs/figures/v1.1.0] [--stepTime 0.01] [--warmup 300]
Reads <benchDir>/manifest.csv for each bench dir (PASS rows only; a (topo, mode, seed) must not appear twice). Every mode uses the same per-step policy window (steps >= warmup).
Throughput = per-step rx * payload bits / step time, from trace.csv, identically for beb / global / independent.
Reward is NOT compared across modes: the trace reward is each mode's own per-AP env reward (not used here).
"""
import argparse
import csv
import json
import os
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from summarize_run import summarize  # noqa: E402

# two-sided 95% Student t critical values, df = 1..10 (no scipy in the venv)
T95 = {1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571, 6: 2.447, 7: 2.365, 8: 2.306, 9: 2.262, 10: 2.228}
MODES = ["beb", "global", "independent", "central"]
LABEL = {"beb": "BEB (802.11)", "global": "Global-CW OSCAR", "independent": "Independent per-AP", "central": "Central critic"}
SHORT = {"beb": "BEB", "global": "Global", "independent": "Indep.", "central": "Central"}
COLOR = {"beb": "#888888", "global": "#d95f02", "independent": "#1b9e77", "central": "#7570b3"}

parser = argparse.ArgumentParser()
parser.add_argument("bench_dirs", nargs="+")
parser.add_argument("--out", default="docs/figures/v1.1.0")
parser.add_argument("--topo", default=None, help="only this apStaCounts value")
parser.add_argument("--title", default="v1.1.0", help="version label used in the tables.md heading")
parser.add_argument("--stepTime", type=float, default=0.01)
parser.add_argument("--warmup", type=int, default=300)
args = parser.parse_args()


def ci(x):
    """(mean, half-width of the 95% CI). Half-width is nan for n < 2."""
    x = np.asarray(x, dtype=float)
    if len(x) < 2:
        return float(x.mean()), float("nan")
    assert len(x) - 1 in T95, "need n <= 11 seeds"
    return float(x.mean()), T95[len(x) - 1] * float(x.std(ddof=1)) / np.sqrt(len(x))


def fmt(x, d=2):
    m, h = ci(x)
    return "%.*f ± %.*f" % (d, m, d, h) if np.isfinite(h) else "%.*f (n=1)" % (d, m)


def convergence_step(tot, win=100, tol=0.05, tail=300):
    """First step after which the rolling-`win` mean of aggregate throughput stays within tol of the last-`tail` mean."""
    roll = np.convolve(tot, np.ones(win) / win, mode="valid")
    ref = tot[-tail:].mean()
    bad = np.where(np.abs(roll - ref) > tol * ref)[0]
    return int(bad[-1] + win) if len(bad) else 0


runs = defaultdict(lambda: defaultdict(dict))  # topo -> mode -> {seed: summary}
for base in args.bench_dirs:
    for r in csv.DictReader(open(os.path.join(base, "manifest.csv"))):
        if r["result"] != "PASS" or (args.topo and r["topo"] != args.topo):
            continue
        cfg = json.load(open(os.path.join(r["run_dir"], "config.json")))
        key = cfg.get("tag") or r["mode"]  # v3.0.0: --tag names a trainer variant; older runs have no tag
        assert int(r["seed"]) not in runs[r["topo"]][key], "duplicate run %s %s %s" % (r["topo"], key, r["seed"])
        s = summarize(r["run_dir"], args.stepTime, args.warmup)
        s["conv"] = convergence_step(s["tot"])
        runs[r["topo"]][key][int(r["seed"])] = s

topos = list(runs)
EXTRA = sorted({m for t in runs for m in runs[t]} - set(MODES))  # tagged variants, after the four base modes
EXTRA_COLORS = ["#e7298a", "#66a61e", "#e6ab02", "#a6761d", "#1f78b4", "#b15928", "#6a3d9a", "#33a02c"]
for i, m in enumerate(EXTRA):
    MODES.append(m)
    LABEL[m] = SHORT[m] = m
    COLOR[m] = EXTRA_COLORS[i % len(EXTRA_COLORS)]
os.makedirs(args.out, exist_ok=True)
md = ["# %s benchmark tables (generated by aggregate_bench.py)" % args.title, "",
      "Policy window = steps >= %d (%.2f s of stepping); mean ± 95%% CI (Student t) over seeds; throughput in Mbps." %
      (args.warmup, args.warmup * args.stepTime), ""]

for topo in topos:
    modes = [m for m in MODES if m in runs[topo]]
    n_aps = len(next(iter(runs[topo][modes[0]].values()))["aps"])
    md += ["## %s STAs per AP" % topo, "",
           "| Mode | n | Aggregate | " + " | ".join("AP%d" % (a + 1) for a in range(n_aps)) +
           " | Phy loss | Jain | " + " | ".join("CW AP%d last-100" % (a + 1) for a in range(n_aps)) + " | Convergence step |",
           "|---|---|---|" + "---|" * (n_aps * 2 + 3)]
    for m in modes:
        S = list(runs[topo][m].values())
        md.append("| %s | %d | %s | %s | %s | %s | %s | %s |" % (
            LABEL[m], len(S), fmt([s["tot_policy"] for s in S]),
            " | ".join(fmt([s["thr_policy"][a] for s in S]) for a in S[0]["aps"]),
            fmt([s["loss_policy"] for s in S], 3), fmt([s["jain_policy"] for s in S], 3),
            " | ".join(fmt([s["cw"][a][-100:].mean() for s in S], 0) for a in S[0]["aps"]),
            fmt([s["conv"] for s in S], 0)))
    md.append("")
    if "beb" in runs[topo]:
        md += ["Paired difference vs BEB (same ns-3 seed), aggregate throughput:", "",
               "| Mode | n pairs | Δ Mbps | Δ % |", "|---|---|---|---|"]
        for m in modes:
            if m == "beb":
                continue
            seeds = sorted(set(runs[topo][m]) & set(runs[topo]["beb"]))
            if not seeds:
                continue
            d = [runs[topo][m][s]["tot_policy"] - runs[topo]["beb"][s]["tot_policy"] for s in seeds]
            p = [100 * x / runs[topo]["beb"][s]["tot_policy"] for x, s in zip(d, seeds)]
            md.append("| %s | %d | %s | %s |" % (LABEL[m], len(seeds), fmt(d), fmt(p, 1)))
        md.append("")
    if "global" in runs[topo]:
        md += ["Paired difference vs Global-CW OSCAR (same ns-3 seed), aggregate throughput and weakest AP:", "",
               "| Mode | n pairs | Δ Mbps | Δ % | Δ min-AP Mbps | above Global |", "|---|---|---|---|---|---|"]
        for m in modes:
            if m in ("beb", "global"):
                continue
            seeds = sorted(set(runs[topo][m]) & set(runs[topo]["global"]))
            if not seeds:
                continue
            g = runs[topo]["global"]
            d = [runs[topo][m][s]["tot_policy"] - g[s]["tot_policy"] for s in seeds]
            p = [100 * x / g[s]["tot_policy"] for x, s in zip(d, seeds)]
            dm = [min(runs[topo][m][s]["thr_policy"].values()) - min(g[s]["thr_policy"].values()) for s in seeds]
            md.append("| %s | %d | %s | %s | %s | %d/%d |" % (LABEL[m], len(seeds), fmt(d), fmt(p, 1), fmt(dm), sum(x > 0 for x in d), len(d)))
        md.append("")
    if "central" in runs[topo] and "independent" in runs[topo]:
        md += ["Paired difference of Central critic vs Independent per-AP (same ns-3 seed), aggregate throughput:", "",
               "| n pairs | Δ Mbps | Δ % | above Independent |", "|---|---|---|---|"]
        seeds = sorted(set(runs[topo]["central"]) & set(runs[topo]["independent"]))
        d = [runs[topo]["central"][s]["tot_policy"] - runs[topo]["independent"][s]["tot_policy"] for s in seeds]
        p = [100 * x / runs[topo]["independent"][s]["tot_policy"] for x, s in zip(d, seeds)]
        md += ["| %d | %s | %s | %d/%d |" % (len(seeds), fmt(d), fmt(p, 1), sum(x > 0 for x in d), len(d)), ""]

with open(os.path.join(args.out, "tables.md"), "w") as f:
    f.write("\n".join(md) + "\n")
print("\n".join(md))

