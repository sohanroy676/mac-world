"""v2.2.0: load sweep plot (aggregate Mbps vs per-STA offered load) from per_seed.csv files written by aggregate_bench.py.
Usage: ../../venv/bin/python load_sweep.py --out <dir> 0.5=<figdir> 1=<figdir> 150=<figdir>
"""
import argparse
import csv
import os
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

T95 = {1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571, 6: 2.447, 7: 2.365, 8: 2.306, 9: 2.262, 10: 2.228}
MODES = ["beb", "global", "independent"]
LABEL = {"beb": "BEB (802.11)", "global": "Global-CW OSCAR", "independent": "Independent per-AP"}
COLOR = {"beb": "#888888", "global": "#d95f02", "independent": "#1b9e77"}

parser = argparse.ArgumentParser()
parser.add_argument("points", nargs="+", help="<load Mbps per STA>=<aggregate_bench output dir>")
parser.add_argument("--out", required=True)
args = parser.parse_args()

data = defaultdict(lambda: defaultdict(dict))  # mode -> load -> {seed: agg}
for p in args.points:
    load, d = p.split("=")
    for r in csv.DictReader(open(os.path.join(d, "per_seed.csv"))):
        data[r["mode"]][float(load)][int(r["seed"])] = float(r["aggregate_mbps"])

os.makedirs(args.out, exist_ok=True)
loads = sorted({l for m in data.values() for l in m})
md = ["# v2.2.0 load sweep, 20,40 (generated by load_sweep.py)", "", "Aggregate Mbps, policy window, mean ± 95% CI over seeds.", "",
      "| Load per STA (Mbps) | " + " | ".join(LABEL[m] for m in MODES) + " | Global vs BEB (paired %) | Independent vs BEB (paired %) |",
      "|---|---|---|---|---|---|"]
fig, ax = plt.subplots(figsize=(7, 4))
for m in MODES:
    ms, hs = [], []
    for l in loads:
        x = np.array(list(data[m][l].values()))
        ms.append(x.mean()); hs.append(T95[len(x) - 1] * x.std(ddof=1) / np.sqrt(len(x)))
    ax.errorbar(loads, ms, yerr=hs, marker="o", capsize=3, label=LABEL[m], color=COLOR[m])
ax.set_xscale("log"); ax.set_xticks(loads); ax.set_xticklabels([str(l) for l in loads])
ax.set_xlabel("Offered load per STA (Mbps)"); ax.set_ylabel("Aggregate throughput (Mbps)")
ax.set_title("20,40: aggregate throughput vs offered load (mean ± 95% CI)"); ax.legend()
fig.tight_layout(); fig.savefig(os.path.join(args.out, "load_sweep.png"), dpi=150)
for l in loads:
    cells = []
    for m in MODES:
        x = np.array(list(data[m][l].values()))
        cells.append("%.2f ± %.2f" % (x.mean(), T95[len(x) - 1] * x.std(ddof=1) / np.sqrt(len(x))))
    for m in ["global", "independent"]:
        seeds = sorted(set(data[m][l]) & set(data["beb"][l]))
        p = np.array([100 * (data[m][l][s] - data["beb"][l][s]) / data["beb"][l][s] for s in seeds])
        cells.append("%+.1f ± %.1f" % (p.mean(), T95[len(p) - 1] * p.std(ddof=1) / np.sqrt(len(p))))
    md.append("| %g | " % l + " | ".join(cells) + " |")
open(os.path.join(args.out, "load_table.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md))
